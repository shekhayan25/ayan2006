// Explain in your own words the difference between encapsulation and abstraction, using examples from any social media app you use daily (like Instagram or WhatsApp).


// 1. Encapsulation:

// Encapsulation means keeping data private and controlling access to it through public methods.

// Example – Instagram:
// Instagram keeps sensitive user information, such as phone number and password, protected. Users cannot directly access or change this private data. They use proper settings or methods to update their information.

// 2. Abstraction:

// Abstraction means hiding the internal working and showing only the important features to the user.

// Example – WhatsApp:
// When we send a message on WhatsApp, we simply click the Send button. We do not need to know how the message is encrypted, transferred through servers, or delivered to the receiver.